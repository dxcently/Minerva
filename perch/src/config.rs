//! The eidolon config the doors run with, and the sessions dir the perch lists.
//!
//! eidolon's `--config <file>` *replaces* `~/.config/eidolon/config.toml` (`Config::load` reads
//! that one file and no other), so a UI door pointed at a config holding two keys would lose
//! every other key the member keeps there. With `--home` the perch therefore **generates**
//! `<home>/config.toml` at every start: the member's own config parsed with a real TOML parser,
//! `sessions_dir` forced to `<home>/sessions` (absolute: eidolon does not expand `~` in that key,
//! and a relative one is relative to each door's cwd), `default_model` filled only when absent.
//! The perch then lists sessions from the same absolute directory it wrote into that file, so the
//! two can never disagree. The files *beside* the config (`providers/`, `policy.rn`, `secrets`)
//! are shared as they always were.

use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};

/// The model a fresh Minerva home starts with when neither the member's config nor
/// `<home>/minerva.toml` names one.
pub const FALLBACK_MODEL: &str = "chatgpt:gpt-5.6-luna";

const HEADER: &str =
    "# generated by minerva perch from ~/.config/eidolon/config.toml; edit that file or ~/Minerva/minerva.toml, not this one\n";

/// What `main` needs once the flags are settled.
#[derive(Debug)]
pub struct Resolved {
    /// The config every door gets as `--config`; `None` when neither `--home` nor `--eidolon-config` was given.
    pub config: Option<PathBuf>,
    /// The one directory doors write kept logs to and the perch lists.
    pub sessions_dir: PathBuf,
    /// The Minerva home, canonical, when `--home` was given.
    pub home: Option<PathBuf>,
}

/// `$XDG_CONFIG_HOME` (absolute) or `$HOME/.config`, plus `eidolon/config.toml`: where
/// `dirs::config_dir()` puts the member's config on Linux, spelled out because the perch takes no `dirs`.
pub fn member_config_path() -> PathBuf {
    let base = std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .filter(|path| path.is_absolute())
        .or_else(|| std::env::var_os("HOME").map(|home| PathBuf::from(home).join(".config")))
        .unwrap_or_else(|| PathBuf::from("."));
    base.join("eidolon").join("config.toml")
}

/// `data_local_dir()/eidolon/sessions`, the door's own default when its config names no
/// `sessions_dir`: `$XDG_DATA_HOME` (absolute) or `$HOME/.local/share`.
pub fn default_sessions_dir() -> PathBuf {
    let data = std::env::var_os("XDG_DATA_HOME")
        .map(PathBuf::from)
        .filter(|path| path.is_absolute())
        .or_else(|| std::env::var_os("HOME").map(|home| PathBuf::from(home).join(".local").join("share")))
        .unwrap_or_else(|| PathBuf::from("."));
    data.join("eidolon").join("sessions")
}

/// eidolon's own sessions dir as it resolves **without** the Minerva config: the `sessions_dir` the member's
/// config names, else [`default_sessions_dir`]. This is the second, read-only source of saved chats under
/// `--home` (the old shared dir, `~/.local/share/eidolon/sessions` unless the member moved it). A member config
/// that cannot be read the way eidolon reads it is the default, which is where eidolon would look too.
pub fn other_sessions_dir(member: &Path) -> PathBuf {
    match sessions_dir_of(member) {
        Ok(Some(dir)) => dir,
        _ => default_sessions_dir(),
    }
}

/// Settles `--home`, `--eidolon-config` and `--sessions-dir` (clap already refuses `--home` with
/// either of the other two). `member` is the member's own config path, read only.
pub fn resolve(home: Option<&Path>, sessions_dir: Option<PathBuf>, eidolon_config: Option<PathBuf>, member: &Path) -> Result<Resolved> {
    if let Some(home) = home {
        std::fs::create_dir_all(home).with_context(|| format!("creating --home {}", home.display()))?;
        let home = home.canonicalize().with_context(|| format!("resolving --home {}", home.display()))?;
        let sessions = home.join("sessions");
        std::fs::create_dir_all(&sessions).with_context(|| format!("creating {}", sessions.display()))?;
        let config = generate(&home, member)?;
        return Ok(Resolved { config: Some(config), sessions_dir: sessions, home: Some(home) });
    }
    let sessions_dir = match (sessions_dir, eidolon_config.as_deref()) {
        (Some(dir), _) => dir,
        (None, Some(config)) => sessions_dir_of(config)?.unwrap_or_else(default_sessions_dir),
        (None, None) => default_sessions_dir(),
    };
    Ok(Resolved { config: eidolon_config, sessions_dir, home: None })
}

/// Writes `<home>/config.toml` (atomically, `0600`) and returns its path. `home` must be absolute.
pub fn generate(home: &Path, member: &Path) -> Result<PathBuf> {
    let mut table = match std::fs::read_to_string(member) {
        Ok(text) => text.parse::<toml::Table>().with_context(|| format!("parsing {}", member.display()))?,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => toml::Table::new(),
        Err(e) => return Err(e).with_context(|| format!("reading {}", member.display())),
    };
    let sessions = home.join("sessions");
    let sessions = sessions.to_str().with_context(|| format!("{} is not UTF-8", sessions.display()))?;
    table.insert("sessions_dir".into(), toml::Value::String(sessions.to_string()));
    if !table.contains_key("default_model") {
        table.insert("default_model".into(), toml::Value::String(minerva_default_model(home)?));
    }
    let body = toml::to_string(&table).context("writing the generated config")?;
    let path = home.join("config.toml");
    harnox::fs::write_atomic_0600(&path, format!("{HEADER}{body}").as_bytes()).with_context(|| format!("writing {}", path.display()))?;
    Ok(path)
}

/// `default_model` from `<home>/minerva.toml`, or [`FALLBACK_MODEL`] when the file or the key is absent.
fn minerva_default_model(home: &Path) -> Result<String> {
    let path = home.join("minerva.toml");
    let text = match std::fs::read_to_string(&path) {
        Ok(text) => text,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(FALLBACK_MODEL.to_string()),
        Err(e) => return Err(e).with_context(|| format!("reading {}", path.display())),
    };
    let table = text.parse::<toml::Table>().with_context(|| format!("parsing {}", path.display()))?;
    match table.get("default_model") {
        None => Ok(FALLBACK_MODEL.to_string()),
        Some(toml::Value::String(model)) if !model.trim().is_empty() => Ok(model.clone()),
        Some(_) => bail!("{}: default_model must be a non-empty string", path.display()),
    }
}

/// The `sessions_dir` an explicit config file names, read as eidolon reads it (a path, no `~`
/// expansion), or `None` when it names none (the door then uses its own default). A missing file is an
/// error, as it is for `eidolon --config`; a relative or `~` value is refused, because the door would
/// resolve it against its own cwd and the perch against another, and new chats would never be listed.
pub fn sessions_dir_of(config: &Path) -> Result<Option<PathBuf>> {
    let text = std::fs::read_to_string(config).with_context(|| format!("reading --eidolon-config {}", config.display()))?;
    let table = text.parse::<toml::Table>().with_context(|| format!("parsing --eidolon-config {}", config.display()))?;
    let dir = match table.get("sessions_dir") {
        None => return Ok(None),
        Some(toml::Value::String(dir)) => PathBuf::from(dir),
        Some(_) => bail!("{}: sessions_dir must be a string", config.display()),
    };
    if !dir.is_absolute() {
        bail!(
            "{}: sessions_dir = {:?} is not an absolute path; eidolon does not expand ~ here and reads a relative one from each \
             door's cwd, so give an absolute path or use --sessions-dir",
            config.display(),
            dir.display().to_string()
        );
    }
    Ok(Some(dir))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn read(path: &Path) -> toml::Table {
        std::fs::read_to_string(path).unwrap().parse().unwrap()
    }

    #[test]
    fn the_members_keys_survive_and_sessions_dir_is_forced() {
        let dir = tempfile::tempdir().unwrap();
        let home = dir.path().join("Minerva");
        std::fs::create_dir(&home).unwrap();
        let member = dir.path().join("member.toml");
        std::fs::write(
            &member,
            "default_model = \"mine\"\nsessions_dir = \"~/old\"\nthinking_budget = 4000\n\n[swarm]\nenabled = false\n\n\
             [[providers]]\nname = \"p\"\nbase_url = \"http://x\"\n",
        )
        .unwrap();
        let path = generate(&home, &member).unwrap();
        let text = std::fs::read_to_string(&path).unwrap();
        assert!(text.starts_with("# generated by minerva perch"), "{text}");
        let table = read(&path);
        assert_eq!(table["sessions_dir"].as_str(), Some(home.join("sessions").to_str().unwrap()), "always overridden");
        assert_eq!(table["default_model"].as_str(), Some("mine"), "the member's model wins over every fallback");
        assert_eq!(table["thinking_budget"].as_integer(), Some(4000));
        assert_eq!(table["swarm"]["enabled"].as_bool(), Some(false), "a table survives");
        assert_eq!(table["providers"][0]["name"].as_str(), Some("p"), "an array of tables survives");
        use std::os::unix::fs::PermissionsExt as _;
        assert_eq!(std::fs::metadata(&path).unwrap().permissions().mode() & 0o777, 0o600);
    }

    #[test]
    fn default_model_falls_back_minerva_toml_then_the_constant() {
        let dir = tempfile::tempdir().unwrap();
        let home = dir.path().join("Minerva");
        std::fs::create_dir(&home).unwrap();
        let none = dir.path().join("absent.toml");
        // No member config, no minerva.toml: an empty table plus the two keys.
        let table = read(&generate(&home, &none).unwrap());
        assert_eq!(table["default_model"].as_str(), Some(FALLBACK_MODEL));
        assert_eq!(table.len(), 2);
        // minerva.toml names one.
        std::fs::write(home.join("minerva.toml"), "default_model = \"mock\"\n").unwrap();
        assert_eq!(read(&generate(&home, &none).unwrap())["default_model"].as_str(), Some("mock"));
        // A minerva.toml without the key is the constant again; a bad one is an error, not a silent fallback.
        std::fs::write(home.join("minerva.toml"), "other = 1\n").unwrap();
        assert_eq!(read(&generate(&home, &none).unwrap())["default_model"].as_str(), Some(FALLBACK_MODEL));
        std::fs::write(home.join("minerva.toml"), "default_model = 3\n").unwrap();
        assert!(generate(&home, &none).is_err());
        // A member config that does not parse is refused rather than dropped.
        std::fs::remove_file(home.join("minerva.toml")).unwrap();
        let broken = dir.path().join("broken.toml");
        std::fs::write(&broken, "default_model = \n").unwrap();
        assert!(format!("{:#}", generate(&home, &broken).unwrap_err()).contains("parsing"));
    }

    #[test]
    fn a_regeneration_replaces_the_file_and_the_sessions_dir_follows_the_home() {
        let dir = tempfile::tempdir().unwrap();
        let home = dir.path().join("Minerva");
        let member = dir.path().join("absent.toml");
        let first = resolve(Some(&home), None, None, &member).unwrap();
        let home = first.home.clone().unwrap();
        assert_eq!(first.sessions_dir, home.join("sessions"));
        assert!(first.sessions_dir.is_dir());
        assert_eq!(first.config.as_deref(), Some(home.join("config.toml").as_path()));
        std::fs::write(home.join("config.toml"), "sessions_dir = \"/hand/edited\"\n").unwrap();
        let again = resolve(Some(&home), None, None, &member).unwrap();
        assert_eq!(sessions_dir_of(again.config.as_deref().unwrap()).unwrap(), Some(home.join("sessions")), "a hand edit is regenerated away");
    }

    #[test]
    fn an_explicit_config_names_the_listing_dir_the_way_eidolon_reads_it() {
        let dir = tempfile::tempdir().unwrap();
        let config = dir.path().join("c.toml");
        let ok = |text: &str| {
            std::fs::write(&config, text).unwrap();
            resolve(None, None, Some(config.clone()), dir.path()).map(|r| r.sessions_dir)
        };
        assert_eq!(ok("sessions_dir = \"/a/b\"\n").unwrap(), PathBuf::from("/a/b"));
        assert_eq!(ok("sessions_dir = '''/lit'''\n").unwrap(), PathBuf::from("/lit"), "TOML spellings a line scan missed");
        assert_eq!(ok("\"sessions_dir\" = \"/quoted/key\"\n").unwrap(), PathBuf::from("/quoted/key"));
        assert_eq!(ok("x = \"\"\"\nsessions_dir = \"/z\"\n\"\"\"\n").unwrap(), default_sessions_dir(), "inside a string is not a key");
        assert_eq!(ok("[swarm]\nsessions_dir = \"/t\"\n").unwrap(), default_sessions_dir(), "a table's key is not the top-level one");
        for bad in ["sessions_dir = \"~/x\"\n", "sessions_dir = \"rel/x\"\n", "sessions_dir = 3\n", "sessions_dir = \n"] {
            assert!(ok(bad).is_err(), "{bad:?} is refused");
        }
        // --sessions-dir still wins, and a missing config is an error.
        assert_eq!(resolve(None, Some("/s".into()), Some(config.clone()), dir.path()).unwrap().sessions_dir, PathBuf::from("/s"));
        assert!(resolve(None, None, Some(dir.path().join("nope.toml")), dir.path()).is_err());
    }
}
