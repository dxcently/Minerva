//! The run's process: the detached `eidolon workflow` child, its own process group, the wall clock, and finding it again (slice R1a).
//!
//! No route here. [`super::state`] decides *what* is started and answered; this file starts it, watches it, stops it and says how it ended.
//!
//! ```text
//!   eidolon --config <home>/runs/<rid>/config.toml workflow run <plugins>/jev <graph> --args - --provider mock          stdin: args.json
//!   eidolon --config <...>/config.toml workflow resume --plugin <plugins>/jev <session> <run> --answer=<text> --provider mock
//! ```
//!
//! **Detached (D3).** A child is its own process group leader, has no `kill_on_drop`, and its stdout and stderr are files in the run's
//! folder (`out.log`, `err.log`, appended), not pipes: when the perch stops, the child neither dies nor loses its output. The perch
//! writes the pid into `runs.json` before it trusts the child (a pid that could not be written is a child that is stopped on the spot),
//! and a perch that starts later takes the run up again in [`adopt`]: a live pid whose `/proc/<pid>/cmdline` names `workflow` and this
//! run's config is watched until it ends; a dead one is settled from what it left. [`on_shutdown`] does not touch a run. What it waits for
//! is the perch's own stop sequences (a cancel's 5 s grace), a second and a half at most.
//!
//! **How a child ends** is told in this order, and the first that applies wins:
//!
//! ```text
//!   the page cancelled it                    cancelled   (even when eidolon says parked or failed on the way out: F0 cases d and l;
//!                                                         a run that had already completed is done)
//!   the wall clock stopped it                failed      "the run took longer than ..."
//!   its stdout's last line (the door's)      completed -> done, parked -> parked, failed -> failed, refused -> refused
//!                                            (a refused resume leaves the run parked, with eidolon's sentence in `refused`)
//!   no such line: the journal, as            a WorkflowEnd of Completed / Failed / Parked, with nothing after it, is that;
//!   `eidolon log --json` prints it           anything else is lost. Only `kind` is read.
//!   no line and no journal                   failed      "eidolon exited with ..."
//! ```
//!
//! **The wall clock** is `--knob run_ms=N` (else `MINERVA_PERCH_RUN_MS`), 15 minutes by default, counted per child: a parked run is waiting
//! for a person, not running. It is measured from the child's start in `runs.json`, so an adopted run keeps its clock. While the perch is
//! down nothing enforces it: a run then has only eidolon's own step budget.
//!
//! **Never a model.** The run's config has `default_model = "mock"` and the argv always has `--provider mock`; there is no `--yolo` and
//! the config is the home's `config.toml` (never the manual one) with only `sessions_dir`, `swarm` and `default_model` changed, so
//! `[policy]` is the member's unchanged and a run shares the permits store the doors use.

