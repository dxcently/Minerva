/// Whether `pid` is an `eidolon ... workflow ...` of this run: its argv (not just a live pid, which may be anyone's now) names `workflow`
/// and the run's own config. A zombie has no argv, so it is not one.
pub(crate) fn is_run(pid: u32, config: &Path) -> bool {
    let Ok(raw) = std::fs::read(format!("/proc/{pid}/cmdline")) else { return false };
    let args: Vec<&[u8]> = raw.split(|b| *b == 0).collect();
    args.contains(&b"workflow".as_slice()) && args.contains(&config.as_os_str().as_encoded_bytes())
}

/// Whether `pid` is a process that is not a zombie (a zombie has no argv, and nothing left to stop).
fn alive(pid: u32) -> bool {
    std::fs::read_to_string(format!("/proc/{pid}/stat")).is_ok_and(|stat| !stat.rsplit_once(')').is_some_and(|(_, rest)| rest.trim_start().starts_with('Z')))
}

/// [`is_run`] for a pid that may have been exec'd an instant ago: until the kernel has set up the new image it shows no argv at all, so a
/// live pid that shows none (or someone else's) is looked at again, a quarter of a second at most, before it is called not ours. A stop
/// that skipped a child it could not yet recognise would leave it running with the run marked as stopping.
async fn is_run_soon(pid: u32, config: &Path) -> bool {
    for _ in 0..10 {
        if is_run(pid, config) {
            return true;
        }
        if !alive(pid) {
            return false;
        }
        tokio::time::sleep(Duration::from_millis(25)).await;
    }
    is_run(pid, config)
}

fn code_of(status: std::process::ExitStatus) -> i32 {
    status.code().unwrap_or_else(|| 128 + status.signal().unwrap_or(0))
}

/// The child the perch started, waited for. If the perch is ending the child is let go (D3) and the next perch settles it.
async fn watch_child(ctx: Ctx, rid: String, mut child: Child, wall: Duration) {
    let exit = tokio::select! {
        waited = child.wait() => waited.ok().map(code_of),
        _ = tokio::time::sleep(wall) => {
            // Over its time: stopped as a cancel is, and told as what it is.
            if let Err(e) = ctx.runs.store.edit(&rid, |run| { run.stop.get_or_insert(Stop::Wall); }) {
                tracing::warn!(error = %format!("{e:#}"), rid, "perch: runs.json could not be written");
            }
            stop(&ctx, &rid);
            match tokio::time::timeout(GRACE + KILL_WAIT + Duration::from_secs(1), child.wait()).await {
                Ok(Ok(status)) => Some(code_of(status)),
                _ => None,
            }
        }
        _ = ctx.stop.cancelled() => return,
    };
    finish(&ctx, &rid, exit).await;
}

/// A child that is not this perch's own (an earlier perch started it), polled until it is gone.
async fn watch_pid(ctx: Ctx, rid: String, pid: u32, config: PathBuf, left: Duration) {
    let deadline = Instant::now() + left;
    let mut stopped = false;
    loop {
        if !is_run(pid, &config) {
            break;
        }
        if !stopped && Instant::now() >= deadline {
            if let Err(e) = ctx.runs.store.edit(&rid, |run| { run.stop.get_or_insert(Stop::Wall); }) {
                tracing::warn!(error = %format!("{e:#}"), rid, "perch: runs.json could not be written");
            }
            stop(&ctx, &rid);
            stopped = true;
        }
        tokio::select! {
            _ = tokio::time::sleep(Duration::from_millis(250)) => {}
            _ = ctx.stop.cancelled() => return,
        }
    }
    finish(&ctx, &rid, None).await;
}

/// SIGTERM to the run's process group, [`GRACE`], then SIGKILL, in a task of its own: the request that asked may be gone.
pub(crate) fn stop(ctx: &Ctx, rid: &str) {
    let (Some(home), Some(run)) = (ctx.registry.home(), ctx.runs.store.get(rid)) else { return };
    let Some(pid) = run.pid else { return };
    let config = home.join("runs").join(rid).join("config.toml");
    ctx.runs.stopping.fetch_add(1, std::sync::atomic::Ordering::SeqCst);
    let ctx = ctx.clone();
    tokio::spawn(async move {
        stop_group(pid, &config).await;
        ctx.runs.stopping.fetch_sub(1, std::sync::atomic::Ordering::SeqCst);
    });
}

/// Only a pid that is still this run's is signalled: the argv is looked at before each signal, so a pid that was reused is left alone.
async fn stop_group(pid: u32, config: &Path) {
    if !is_run_soon(pid, config).await {
        return;
    }
    unsafe { libc::killpg(pid as libc::pid_t, libc::SIGTERM) };
    let until = Instant::now() + GRACE;
    while Instant::now() < until && is_run(pid, config) {
        tokio::time::sleep(Duration::from_millis(25)).await;
    }
    if is_run(pid, config) {
        unsafe { libc::killpg(pid as libc::pid_t, libc::SIGKILL) };
        let until = Instant::now() + KILL_WAIT;
        while Instant::now() < until && is_run(pid, config) {
            tokio::time::sleep(Duration::from_millis(25)).await;
        }
    }
}

/// After the bind (lib.rs): open `<home>/runs.json` and take up again the runs a previous perch left detached (D3). The settling runs
/// in tasks: the perch serves at once, and a run that is still being looked at is simply `running` until it has been.
pub fn adopt(ctx: &Ctx) {
    let Some(home) = ctx.registry.home() else { return };
    ctx.runs.store.open(home.join("runs.json"));
    for (rid, run) in ctx.runs.store.all() {
        if run.state != Phase::Running {
            continue;
        }
        let config = home.join("runs").join(&rid).join("config.toml");
        match run.pid {
            Some(pid) if is_run(pid, &config) => {
                if run.stop.is_some() {
                    // A stop that the last perch did not finish: the group is told again.
                    stop(ctx, &rid);
                }
                let spent = Duration::from_millis(crate::archive::now_ms().saturating_sub(run.child_ms.unwrap_or_else(crate::archive::now_ms)));
                tokio::spawn(watch_pid(ctx.clone(), rid, pid, config, wall(ctx).saturating_sub(spent)));
            }
            // The child ended, or was never started, while no perch was looking: told from what it left.
            _ => {
                let ctx = ctx.clone();
                tokio::spawn(async move { finish(&ctx, &rid, None).await });
            }
        }
    }
}

/// At shutdown, after the terminals and before the doors (serve.rs). A detached run is **not** killed here (D3): it outlives the perch
/// and the next one adopts it. What this waits for is only what the perch itself owns, a stop it has begun, and it bounds its own wait.
pub async fn on_shutdown(ctx: &Ctx) {
    let until = Instant::now() + SHUTDOWN_WAIT;
    while ctx.runs.stopping.load(std::sync::atomic::Ordering::SeqCst) > 0 && Instant::now() < until {
        tokio::time::sleep(Duration::from_millis(25)).await;
    }
}

