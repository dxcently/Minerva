    fn rec(id: u64, kind: &str) -> String {
        format!("{{\"id\":{id},\"parent\":null,\"ts_ms\":1,\"kind\":{kind}}}\n")
    }

    #[test]
    fn the_journal_is_read_for_its_end_and_nothing_else() {
        let start = rec(1, "{\"WorkflowStart\":{\"plugin\":\"jev\"}}");
        let step = rec(2, "{\"WorkflowStep\":{\"tool\":\"WorkflowEnd\"}}");
        let end = |status: &str| rec(9, &format!("{{\"WorkflowEnd\":{{\"run\":1,\"status\":\"{status}\"}}}}"));
        let read = |text: String| read_journal(text.as_bytes());
        let done = read(format!("{start}{step}{}", end("Completed")));
        assert_eq!((done.end, done.after_end, done.run), (Some(End::Completed), false, Some(1)));
        assert_eq!(read(format!("{start}{}", end("Failed"))).end, Some(End::Failed));
        assert_eq!(read(format!("{start}{}", end("Parked"))).end, Some(End::Parked));
        assert_eq!(read(format!("{start}{step}")).end, None, "SIGKILL leaves no end (F0 k)");
        // A resumed run that was cut again: the park is not its end any more.
        let cut = read(format!("{start}{}{step}", end("Parked")));
        assert_eq!((cut.end, cut.after_end), (Some(End::Parked), true));
        // The word in a tool's name or a result is not a record's kind.
        assert_eq!(read(format!("{start}{step}")).end, None);
        let odd = read(format!("{start}{}", end("Cancelled")));
        assert!((odd.end, odd.strange) == (None, true));
        assert_eq!(read(String::new()), Journal::default());
        assert_eq!(read_journal(format!("{start}{}", end("Completed")).replace('\n', "\r\n").as_bytes()).end, Some(End::Completed), "CRLF is fine");
    }

