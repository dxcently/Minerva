    #[test]
    fn a_pid_is_a_run_only_while_its_argv_says_so() {
        let config = Path::new("/h/runs/r1/config.toml");
        assert!(!is_run(std::process::id(), config), "this test process is not a workflow of that config");
        assert!(!is_run(u32::MAX, config), "no such pid");
        let mut sleeper = std::process::Command::new("sh").args(["-c", "sleep 5; true", "workflow"]).arg(config).spawn().unwrap();
        // Not at the first look: for an instant after the exec the kernel shows a new process no argv (see `is_run_soon`).
        let until = Instant::now() + Duration::from_secs(2);
        while !is_run(sleeper.id(), config) && Instant::now() < until {
            std::thread::sleep(Duration::from_millis(5));
        }
        assert!(is_run(sleeper.id(), config), "argv with `workflow` and the config path");
        assert!(!is_run(sleeper.id(), Path::new("/h/runs/r2/config.toml")), "another run's config is not this run");
        sleeper.kill().unwrap();
        sleeper.wait().unwrap();
        assert!(!is_run(sleeper.id(), config), "gone");
    }

    #[tokio::test]
    async fn a_pid_that_has_only_just_been_exec_d_is_still_found_and_someone_elses_is_not() {
        let config = Path::new("/h/runs/r1/config.toml");
        let mut sleeper = std::process::Command::new("sh").args(["-c", "sleep 5; true", "workflow"]).arg(config).spawn().unwrap();
        assert!(is_run_soon(sleeper.id(), config).await, "asked at the first instant, it is waited for");
        // A live process that is not this run is not found, and it takes the bounded wait to say so; a pid that is gone does not wait.
        let asked = Instant::now();
        assert!(!is_run_soon(std::process::id(), config).await);
        assert!(asked.elapsed() < Duration::from_secs(2), "{:?}", asked.elapsed());
        sleeper.kill().unwrap();
        sleeper.wait().unwrap();
        let asked = Instant::now();
        assert!(!is_run_soon(sleeper.id(), config).await);
        assert!(asked.elapsed() < Duration::from_millis(100), "a pid that is gone is not waited for: {:?}", asked.elapsed());
        assert!(alive(std::process::id()) && !alive(sleeper.id()) && !alive(u32::MAX));
    }

