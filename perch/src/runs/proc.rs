/// How long SIGTERM is given before SIGKILL, for a cancel and for the wall clock.
pub const GRACE: Duration = Duration::from_secs(5);
/// After SIGKILL, how long the child is waited for.
const KILL_WAIT: Duration = Duration::from_secs(2);
/// A child's wall clock, unless `--knob run_ms=<ms>` says otherwise.
pub const WALL: Duration = Duration::from_secs(15 * 60);
/// What a shutdown waits for the perch's own stop sequences, at most (the serve loop bounds its hook at 3 s).
const SHUTDOWN_WAIT: Duration = Duration::from_millis(2500);
/// How much of a child's output a row shows.
const TAIL: u64 = 4096;
/// The door's line is the last of at most this much of the child's own output.
const DOOR_WINDOW: u64 = 1024 * 1024;

const HEADER: &str = "# generated by minerva perch for one graph run: the home's config.toml with this folder as sessions_dir, the swarm off and the mock model\n";

pub(crate) fn wall(ctx: &Ctx) -> Duration {
    let asked = ctx.opts.knobs.get("run_ms").map(str::to_string).or_else(|| std::env::var("MINERVA_PERCH_RUN_MS").ok());
    asked.and_then(|ms| ms.trim().parse().ok()).map(Duration::from_millis).unwrap_or(WALL)
}

