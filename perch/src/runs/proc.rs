/// `config` (the text of the home's `config.toml`) as one run's: its folder is the sessions dir, so the run's journal is the only
/// `.eid` there and the run never joins the roster; the swarm is off; the model is the mock. Parsed and displayed, never edited by hand,
/// and every other table (`[policy]` above all) goes through as it was.
pub(crate) fn run_config(config: &str, dir: &Path) -> Result<String> {
    let mut table = config.parse::<toml::Table>().context("the home's config.toml does not parse")?;
    let dir = dir.to_str().with_context(|| format!("{} is not UTF-8", dir.display()))?;
    table.insert("sessions_dir".into(), toml::Value::String(dir.to_string()));
    table.insert("default_model".into(), toml::Value::String("mock".to_string()));
    let swarm = table.entry("swarm").or_insert_with(|| toml::Value::Table(toml::Table::new()));
    let Some(swarm) = swarm.as_table_mut() else { bail!("the home's config.toml has a [swarm] that is not a table") };
    swarm.insert("enabled".into(), toml::Value::Boolean(false));
    Ok(format!("{HEADER}{}", toml::to_string(&table).context("writing the run's config")?))
}

/// Writes the run's `config.toml` and `args.json` (both `0600`) into its folder and opens the args as the child's stdin.
pub(crate) fn prepare(home: &Path, rid: &str, args: &[u8]) -> Result<File> {
    let dir = home.join("runs").join(rid);
    let base = home.join("config.toml");
    let text = std::fs::read_to_string(&base).with_context(|| format!("reading {}", base.display()))?;
    let config = run_config(&text, &dir)?;
    harnox::fs::write_atomic_0600(&dir.join("config.toml"), config.as_bytes()).context("writing the run's config.toml")?;
    harnox::fs::write_atomic_0600(&dir.join("args.json"), args).context("writing the run's args.json")?;
    File::open(dir.join("args.json")).context("opening the run's args.json")
}

fn os(text: impl Into<OsString>) -> OsString {
    text.into()
}

