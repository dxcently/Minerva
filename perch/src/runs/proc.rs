/// The door's last stdout line: eidolon's one JSON line (`status` is `completed`, `parked`, `failed` or `refused`).
#[derive(Deserialize, Default)]
struct Door {
    #[serde(default)]
    status: String,
    question: Option<String>,
    report: Option<String>,
    reason: Option<String>,
    error: Option<String>,
    run: Option<u64>,
    session: Option<String>,
}

/// The last line of `out.log` past `from` that is a door line.
fn door_line(path: &Path, from: u64) -> Option<Door> {
    let mut file = File::open(path).ok()?;
    let len = file.metadata().ok()?.len();
    let start = from.max(len.saturating_sub(DOOR_WINDOW)).min(len);
    file.seek(SeekFrom::Start(start)).ok()?;
    let mut bytes = Vec::new();
    file.take(DOOR_WINDOW).read_to_end(&mut bytes).ok()?;
    String::from_utf8_lossy(&bytes).lines().rev().filter_map(|line| serde_json::from_str::<Door>(line.trim()).ok()).find(|door| !door.status.is_empty())
}

/// The journal's own word for how a run ended.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum End {
    Completed,
    Failed,
    Parked,
}

/// What `eidolon log --json` says of a run: how it ended, if it did, and whether anything came after that, and the run's number (the id
/// of its `WorkflowStart`). Only each record's `kind` is read, and only the kind's name and a `WorkflowEnd`'s `status`.
#[derive(Debug, Default, PartialEq, Eq)]
pub(crate) struct Journal {
    pub end: Option<End>,
    /// A `WorkflowEnd` the journal has, of a word this perch does not know.
    pub strange: bool,
    pub after_end: bool,
    pub run: Option<u64>,
}

pub(crate) fn read_journal(text: &[u8]) -> Journal {
    let (mut journal, mut at_end, mut last) = (Journal::default(), None, 0usize);
    for (n, line) in text.split(|b| *b == b'\n').enumerate() {
        let line = line.strip_suffix(b"\r").unwrap_or(line);
        if line.is_empty() {
            continue;
        }
        last = n;
        let named = |word: &[u8]| line.windows(word.len()).any(|w| w == word);
        if !(named(b"WorkflowEnd") || named(b"WorkflowStart")) {
            continue;
        }
        let Ok(record) = serde_json::from_slice::<Value>(line) else { continue };
        let Some(kind) = record.get("kind") else { continue };
        if journal.run.is_none() && kind.get("WorkflowStart").is_some() {
            journal.run = record.get("id").and_then(Value::as_u64);
        }
        if let Some(end) = kind.get("WorkflowEnd") {
            at_end = Some(n);
            (journal.end, journal.strange) = match end.get("status").and_then(Value::as_str) {
                Some("Completed") => (Some(End::Completed), false),
                Some("Failed") => (Some(End::Failed), false),
                Some("Parked") => (Some(End::Parked), false),
                _ => (None, true),
            };
        }
    }
    journal.after_end = at_end.is_some_and(|at| last > at);
    journal
}

/// The run's journal through eidolon's own `log --json`: the perch does not read the file.
async fn journal(ctx: &Ctx, config: &Path, session: &Path) -> Option<Journal> {
    let args = [os("log"), os("--json"), session.as_os_str().to_os_string()];
    let out = crate::titles::run(&ctx.registry.eidolon, Some(config), &args, crate::titles::LOG_CAP, crate::titles::LOG_TIMEOUT).await.ok()?;
    Some(read_journal(&out))
}

/// The newest `*.eid` in the run's folder: the session eidolon made for it. Found by name; the file is not opened.
pub(crate) fn find_session(dir: &Path) -> Option<PathBuf> {
    let mut found: Vec<PathBuf> = std::fs::read_dir(dir)
        .ok()?
        .flatten()
        .filter(|entry| entry.path().extension().is_some_and(|ext| ext == "eid") && entry.file_type().is_ok_and(|kind| kind.is_file()))
        .map(|entry| entry.path())
        .collect();
    found.sort();
    found.pop()
}

/// The last [`TAIL`] bytes of a child's output, as text.
pub(crate) fn tail(path: &Path) -> String {
    let read = || -> std::io::Result<Vec<u8>> {
        let mut file = File::open(path)?;
        let len = file.metadata()?.len();
        file.seek(SeekFrom::Start(len.saturating_sub(TAIL)))?;
        let mut bytes = Vec::new();
        file.take(TAIL).read_to_end(&mut bytes)?;
        Ok(bytes)
    };
    let text = String::from_utf8_lossy(&read().unwrap_or_default()).into_owned();
    // A cut that fell inside a character leaves its broken start behind.
    text.trim_start_matches('\u{fffd}').to_string()
}

/// What a finished child leaves on its run.
struct Verdict {
    phase: Phase,
    why: Option<String>,
    question: Option<String>,
    report: Option<String>,
    refused: Option<String>,
    session: Option<PathBuf>,
    eid_run: Option<u64>,
}

impl Verdict {
    fn apply(self, run: &mut Run, exit: Option<i32>) {
        run.state = self.phase;
        run.pid = None;
        run.child_ms = None;
        run.stop = None;
        run.exit = exit;
        run.why = self.why;
        run.report = self.report;
        run.refused = self.refused;
        // A park keeps the question it has (a refused resume says nothing new); an end has no question.
        match self.phase {
            Phase::Parked => run.question = self.question.or(run.question.take()),
            _ => run.question = None,
        }
        if self.session.is_some() {
            run.session = self.session;
        }
        if self.eid_run.is_some() {
            run.eid_run = self.eid_run;
        }
        run.ended_ms = (!self.phase.holds()).then(crate::archive::now_ms);
    }
}

fn describe(exit: Option<i32>) -> String {
    match exit {
        Some(code) if code > 128 => format!("was killed by signal {}", code - 128),
        Some(code) => format!("exited with {code}"),
        None => "is gone".to_string(),
    }
}

/// How the child that was just reaped (or found gone) ended. See the module doc for the order.
async fn decide(ctx: &Ctx, dir: &Path, run: &Run, exit: Option<i32>) -> Verdict {
    let door = door_line(&dir.join("out.log"), run.out_off);
    let session = door
        .as_ref()
        .and_then(|door| door.session.as_deref())
        .map(PathBuf::from)
        .filter(|path| path.parent() == Some(dir) && path.extension().is_some_and(|ext| ext == "eid"))
        .or_else(|| run.session.clone())
        .or_else(|| find_session(dir));
    let eid_run = door.as_ref().and_then(|door| door.run).or(run.eid_run);
    let said = door.as_ref().map(|door| door.status.as_str());
    let base = |phase| Verdict { phase, why: None, question: None, report: None, refused: None, session: session.clone(), eid_run };
    match run.stop {
        Some(Stop::Wall) => {
            return Verdict { why: Some(format!("the run took longer than {} and was stopped", spoken(wall(ctx)))), ..base(Phase::Failed) };
        }
        // A run that had finished its work when the cancel arrived is done: that is what happened to it.
        Some(Stop::Cancel) if said != Some("completed") => return base(Phase::Cancelled),
        _ => {}
    }
    if let Some(door) = &door {
        match door.status.as_str() {
            "completed" => return Verdict { report: kept(door.report.as_deref()), ..base(Phase::Done) },
            "parked" => return Verdict { question: kept(door.question.as_deref()), ..base(Phase::Parked) },
            "failed" => {
                let why = door.reason.clone().unwrap_or_else(|| "the graph ended failed".to_string());
                return Verdict { why: kept(Some(why.as_str())), ..base(Phase::Failed) };
            }
            "refused" => {
                let error = kept(Some(door.error.as_deref().unwrap_or("eidolon refused"))).unwrap_or_default();
                // A refusal of a *resume* changes nothing in the journal: the run is still parked (F0 c, g, j). Of a start: nothing ran.
                return if run.resumes > 0 { Verdict { refused: Some(error), ..base(Phase::Parked) } } else { Verdict { why: Some(error), ..base(Phase::Refused) } };
            }
            _ => {}
        }
    }
    // No verdict line: the journal is the next witness.
    let Some(session) = session.clone() else {
        let said = tail_words(&tail(&dir.join("err.log")));
        let why = format!("eidolon {} before it made a journal{}", describe(exit), if said.is_empty() { String::new() } else { format!(": {said}") });
        return Verdict { why: Some(why), ..base(Phase::Failed) };
    };
    match journal(ctx, &dir.join("config.toml"), &session).await {
        Some(j) => {
            let verdict = |phase, why: Option<&str>| Verdict { why: why.map(str::to_string), eid_run: eid_run.or(j.run), ..base(phase) };
            match (j.end, j.after_end) {
                (Some(End::Completed), false) => verdict(Phase::Done, None),
                (Some(End::Failed), false) => verdict(Phase::Failed, Some("the run ended failed; eidolon did not say why")),
                (Some(End::Parked), false) => verdict(Phase::Parked, None),
                _ => {
                    let why = format!("eidolon {} and the journal has no end", describe(exit));
                    verdict(Phase::Lost, Some(&why))
                }
            }
        }
        None => Verdict { why: Some(format!("eidolon {} and its journal could not be read", describe(exit))), ..base(Phase::Lost) },
    }
}

/// A child is gone: say how it ended, once.
async fn finish(ctx: &Ctx, rid: &str, exit: Option<i32>) {
    let (Some(home), Some(run)) = (ctx.registry.home(), ctx.runs.store.get(rid)) else { return };
    let dir = home.join("runs").join(rid);
    let verdict = decide(ctx, &dir, &run, exit).await;
    if let Err(e) = ctx.runs.store.edit(rid, |run| verdict.apply(run, exit)) {
        tracing::warn!(error = %format!("{e:#}"), rid, "perch: runs.json could not be written");
    }
}

